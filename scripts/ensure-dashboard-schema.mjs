import postgres from "postgres";

const sql = postgres({
  host: process.env.PG_HOST,
  port: Number(process.env.PG_PORT || 5432),
  database: process.env.PG_DB,
  username: process.env.PG_USER,
  password: process.env.PG_PASSWORD,
  ssl: process.env.PG_SSLMODE === "disable" ? false : "require",
  max: 1,
  connect_timeout: 15,
});

try {
  await sql.begin(async (transaction) => {
    await transaction.unsafe(`
      create table if not exists public.investidor_remuneracao (
        id bigint generated by default as identity primary key,
        investidor_id bigint not null references public.investidores(investidor_id) on delete restrict,
        investidor_nome varchar(255) not null,
        remuneracao numeric(14,2) not null check (remuneracao >= 0),
        data_inicio_vigencia date not null,
        data_fim_vigencia date,
        created_at timestamptz not null default now(),
        updated_at timestamptz not null default now(),
        constraint investidor_remuneracao_periodo_valido
          check (data_fim_vigencia is null or data_fim_vigencia >= data_inicio_vigencia)
      )
    `);
    await transaction.unsafe(`
      create index if not exists investidor_remuneracao_investidor_periodo_idx
      on public.investidor_remuneracao (investidor_id, data_inicio_vigencia, data_fim_vigencia)
    `);
    await transaction.unsafe(`
      create table if not exists public.economics_config (
        id integer primary key,
        imposto_percentual numeric(8,4) not null default 9,
        royalties_percentual numeric(8,4) not null default 15,
        cluster_small_ate numeric(14,2) not null default 5000,
        cluster_medium_ate numeric(14,2) not null default 10000,
        cluster_large_ate numeric(14,2) not null default 20000,
        meta_csp numeric(12,4) not null default 0.5,
        meta_rpco numeric(14,2) not null default 12000,
        meta_mc numeric(12,4) not null default 0.5,
        meta_nrr numeric(12,4) not null default 1,
        updated_at timestamptz not null default now()
      )
    `);
    await transaction.unsafe(`
      insert into public.economics_config (id)
      values (1)
      on conflict (id) do nothing
    `);
  });
  console.log("Dashboard schema ready.");
} finally {
  await sql.end();
}
